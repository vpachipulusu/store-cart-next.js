type E2eCredentialName =
  | 'TEST_USER_EMAIL'
  | 'TEST_USER_PASSWORD'
  | 'TEST_ADMIN_EMAIL'
  | 'TEST_ADMIN_PASSWORD';

/** Read when used, not at import, so the env loaded by playwright.config is always seen. */
const readE2eCredentials = (): Record<E2eCredentialName, string | undefined> => ({
  TEST_USER_EMAIL: process.env.TEST_USER_EMAIL,
  TEST_USER_PASSWORD: process.env.TEST_USER_PASSWORD,
  TEST_ADMIN_EMAIL: process.env.TEST_ADMIN_EMAIL,
  TEST_ADMIN_PASSWORD: process.env.TEST_ADMIN_PASSWORD,
});

/**
 * Read a required e2e credential from the environment. There is no default: the accounts are generated by
 * `npm run test:setup` into `.env.e2e.local` (or come from CI secrets). Throws naming the VARIABLE, never a value.
 */
function requiredEnv(name: E2eCredentialName): string {
  const value = readE2eCredentials()[name];
  if (!value) {
    throw new Error(
      `${name} is not set. Run \`npm run test:setup\` (writes .env.e2e.local) or set it in the environment.`
    );
  }
  return value;
}

